class Air
{
    public static void main(String[] args)
    {
        String type = "Fresh Air";
        String color = "Colorless";
        int temperature = 25;
        String smell = "Odorless";
        boolean visible = false;
        int pressure = 1013;
        String state = "Gas";
        double humidity = 60.5;
        String location = "Bengaluru";
        boolean breathable = true;

        System.out.println("Type: " + type);
        System.out.println("Color: " + color);
        System.out.println("Temperature: " + temperature);
        System.out.println("Smell: " + smell);
        System.out.println("Visible: " + visible);
        System.out.println("Pressure: " + pressure);
        System.out.println("State: " + state);
        System.out.println("Humidity: " + humidity);
        System.out.println("Location: " + location);
        System.out.println("Breathable: " + breathable);
    }
}