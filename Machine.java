class Machine {

    static void started() {
        System.out.println("Machine is started");
    }

    static void running() {
        System.out.println("Machine is running");
    }

    static void working() {
        System.out.println("Machine is working");
    }

    static void repaired() {
        System.out.println("Machine is repaired");
    }

    static void switchedOff() {
        System.out.println("Machine is switched off");
    }
}